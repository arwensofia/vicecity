int main(int argc, char **argv)
{
	std::string elf_path, csv_path, out_dir, cfg_path, names_path, modules_path;
	size_t nfiles = 64;
	bool discover = true, quiet = false;
	uint32_t disasm_addr = 0, disasm_count = 0;
	EmitOptions opt;
	for (int k = 1; k < argc; k++) {
		std::string a = argv[k];
		auto next = [&]() -> std::string {
			if (k + 1 >= argc) {
				usage();
				std::exit(2);
			}
			return argv[++k];
		};
		try {
			if (a == "--elf") elf_path = next();
			else if (a == "--functions") csv_path = next();
			else if (a == "--out") out_dir = next();
			else if (a == "--config") cfg_path = next();
			else if (a == "--names") names_path = next();
			else if (a == "--modules") modules_path = next();
			else if (a == "--files") nfiles = std::stoul(next());
			else if (a == "--no-comments") opt.comments = false;
			else if (a == "--no-trace-points") opt.trace_points = false;
			else if (a == "--no-discover") discover = false;
			else if (a == "--quiet") quiet = true;
			else if (a == "--disasm") {
				disasm_addr = parse_hex(next());
				disasm_count = static_cast<uint32_t>(std::stoul(next(), nullptr, 0));
			} else {
				usage();
				return 2;
			}
		} catch (...) {
			usage();
			return 2;
		}
	}
	if (elf_path.empty() || (!disasm_count && (csv_path.empty() || out_dir.empty())) || nfiles < 1 || nfiles > 4096) {
		usage();
		return 2;
	}
	auto t0 = std::chrono::steady_clock::now();

	Image img;
	std::string err;
	if (!img.load_elf(elf_path, err)) {
		std::fprintf(stderr, "ps2recomp: %s\n", err.c_str());
		return 1;
	}
	if (disasm_count) {
		for (uint32_t n = 0; n < disasm_count; n++) {
			uint32_t a = disasm_addr + 4 * n, w;
			if (!img.read32(a, w)) break;
			std::printf("%08x  %08x  %s\n", a, w, disasm(decode(a, w)).c_str());
		}
		return 0;
	}
	std::vector<FunctionDef> defs;
	if (!load_function_csv(csv_path, defs, err)) {
		std::fprintf(stderr, "ps2recomp: %s\n", err.c_str());
		return 1;
	}
	std::map<uint32_t, Symbol> syms;
	if (!names_path.empty() && !load_library_names(names_path, syms, err)) {
		std::fprintf(stderr, "ps2recomp: %s\n", err.c_str());
		return 1;
	}
	std::map<uint32_t, std::string> modules;
	if (!modules_path.empty() && !load_modules(modules_path, modules, err)) {
		std::fprintf(stderr, "ps2recomp: %s\n", err.c_str());
		return 1;
	}

	// ---- configuration (exclusions, constructor tables) -------------------
	std::vector<uint32_t> ctor_tables;
	std::vector<std::pair<uint32_t, uint32_t>> code_ranges; // where address-taken entries may be created
	if (!cfg_path.empty()) {
		std::ifstream cf(cfg_path);
		if (!cf) {
			std::fprintf(stderr, "ps2recomp: cannot open %s\n", cfg_path.c_str());
			return 1;
		}
		std::string line;
		while (std::getline(cf, line)) {
			line = line.substr(0, line.find('#'));
			std::istringstream ls(line);
			std::string kw, a, b;
			if (!(ls >> kw)) continue;
			try {
				if (kw == "exclude" && ls >> a >> b) {
					img.excluded.emplace_back(parse_hex(a), parse_hex(b));
				} else if (kw == "code" && ls >> a >> b) {
					code_ranges.emplace_back(parse_hex(a), parse_hex(b));
				} else if (kw == "ctors" && ls >> a) {
					ctor_tables.push_back(parse_hex(a));
				} else {
					std::fprintf(stderr, "ps2recomp: bad config line: %s\n", line.c_str());
					return 1;
				}
			} catch (...) {
				std::fprintf(stderr, "ps2recomp: bad number in config line: %s\n", line.c_str());
				return 1;
			}
		}
	}
	std::vector<uint32_t> ctors;
	for (uint32_t t : ctor_tables) {
		for (uint32_t k = 0; k < 4096; k++) {
			uint32_t v;
			if (!img.read32(t + 4 * k, v) || v == 0) break;
			if (v == 0xFFFFFFFFu && k == 0) continue; // GCC count/sentinel word
			if (!img.is_code(v)) {
				std::fprintf(stderr, "ps2recomp: ctors entry %08x at %08x is not code\n", v, t + 4 * k);
				break;
			}
			ctors.push_back(v);
		}
	}

	// ---- entry discovery -------------------------------------------------
	std::map<uint32_t, std::string> why; // entry -> origin comment
	std::set<uint32_t> entries;
	size_t csv_rejected = 0, csv_excluded = 0;
	for (const FunctionDef &d : defs) {
		if (img.is_excluded(d.addr)) {
			csv_excluded++;
			continue;
		}
		if (!img.is_code(d.addr)) {
			csv_rejected++;
			continue;
		}
		entries.insert(d.addr);
		why[d.addr] = d.name;
		// Ghidra names other than FUN_xxxxxxxx are real names (debug-string derived).
		if (d.name.rfind("FUN_", 0) != 0 && !d.name.empty()) {
			Symbol &s = syms[d.addr];
			if (s.rank < 50) {
				s.name = d.name;
				s.rank = 50;
			}
		}
	}
	const size_t csv_entries = entries.size();
	if (img.is_code(img.entry) && entries.insert(img.entry).second) why[img.entry] = "ELF entry";
	size_t ctor_new = 0;
	for (uint32_t v : ctors)
		if (entries.insert(v).second) {
			why[v] = "static constructor (.ctors)";
			ctor_new++;
		}

	std::map<std::pair<uint32_t, uint32_t>, FuncAnalysis> acache;
	auto analyze = [&](uint32_t e, uint32_t limit) -> const FuncAnalysis & {
		auto key = std::make_pair(e, limit);
		auto it = acache.find(key);
		if (it == acache.end()) it = acache.emplace(key, analyze_function(img, e, limit)).first;
		return it->second;
	};
	auto limit_of = [&](uint32_t e) {
		auto it = entries.upper_bound(e);
		uint32_t end = img.code_end(e);
		for (const auto &[a, b] : img.excluded)
			if (a > e) end = std::min(end, a);
		return it == entries.end() ? end : std::min(*it, end);
	};

	int passes = 0;
	size_t discovered_branch = 0;
	auto fixpoint = [&]() {
		std::map<uint32_t, std::string> found;
		for (;;) {
			passes++;
			std::set<uint32_t> fresh;
			for (uint32_t e : entries) {
				const FuncAnalysis &fa = analyze(e, limit_of(e));
				for (uint32_t t : fa.calls)
					if (img.is_code(t) && !img.is_excluded(t) && !entries.count(t) && fresh.insert(t).second)
						found[t] = "discovered: call target from " + hex(e);
				for (uint32_t t : fa.ext_targets)
					if (img.is_code(t) && !img.is_excluded(t) && !entries.count(t) && fresh.insert(t).second)
						found[t] = "discovered: branch target from " + hex(e);
			}
			if (fresh.empty() || passes > 64) break;
			for (uint32_t t : fresh) {
				entries.insert(t);
				why[t] = found[t];
				discovered_branch++;
			}
		}
	};
	if (discover) fixpoint();

	// Address-taken code that no analysed function reaches: function pointers
	// (callbacks, vtables) to functions missing from the CSV. Accepted when the
	// target follows a function terminator (possibly padded with nops) and is
	// not a hole inside the referencing function's own body (those are labels,
	// e.g. __builtin_setjmp receivers -- reported, not made entries).
	auto in_code_range = [&](uint32_t a) {
		if (code_ranges.empty()) return img.in_exec_section(a);
		for (const auto &[x, y] : code_ranges)
			if (a >= x && a < y) return img.is_code(a);
		return false;
	};
	std::vector<std::pair<uint32_t, uint32_t>> taken_added;    // target, first site
	std::vector<std::pair<uint32_t, uint32_t>> internal_ptrs;  // target, site
	if (discover) {
		auto owner = [&](uint32_t a) -> uint32_t {
			auto it = entries.upper_bound(a);
			return it == entries.begin() ? 0 : *std::prev(it);
		};
		// Follows a function terminator (jr / j / b / eret + delay slot), possibly
		// padded with nops.
		auto entry_like = [&](uint32_t a) {
			for (uint32_t k = 2; k <= 10; k++) {
				uint32_t p = a - 4 * k, w;
				if (!img.read32(p, w)) return false;
				Insn i = decode(p, w);
				bool term = i.op == Op::JR || i.op == Op::J || i.op == Op::ERET || (i.op == Op::BEQ && i.rs == i.rt);
				if (term) {
					for (uint32_t q = p + 8; q < a; q += 4) {
						uint32_t x;
						if (!img.read32(q, x) || x != 0) return false;
					}
					return true;
				}
			}
			return false;
		};
		std::set<uint32_t> internal_seen;
		// Phase 0: code constants (lui/addiu, lui/ori) until nothing new; then
		// phase 1: data words. Data words that form a jump-table-like run (two or
		// more consecutive code pointers spanning < 4 KB) are skipped: their
		// targets are switch labels of a function that may not be known yet.
		for (int phase = 0; phase < 2; phase++) {
			for (int round = 0; round < 8; round++) {
				std::vector<uint8_t> covered(img.segments.empty() ? 0 : 0x01000000, 0); // bit per word below 64 MB
				auto cov = [&](uint32_t x) { return (x >> 2) < covered.size() * 8 && (covered[x >> 5] >> ((x >> 2) & 7) & 1); };
				auto set_cov = [&](uint32_t x) { if ((x >> 2) < covered.size() * 8) covered[x >> 5] |= static_cast<uint8_t>(1u << ((x >> 2) & 7)); };
				std::map<uint32_t, uint32_t> extent; // entry -> end of reached code
				std::vector<CodeRef> refs;
				for (uint32_t e : entries) {
					const FuncAnalysis &fa = analyze(e, limit_of(e));
					for (const auto &kv : fa.insns) set_cov(kv.first);
					extent[e] = fa.end();
					if (phase == 0) scan_code_constants(fa, refs);
				}
				if (phase == 1) {
					for (const Segment &sg : img.segments) {
						std::vector<std::pair<uint32_t, uint32_t>> run; // (word addr, value)
						auto flush_run = [&]() {
							uint32_t mn = ~0u, mx = 0;
							for (auto &[at, v] : run) mn = std::min(mn, v), mx = std::max(mx, v);
							if (!kSkipTableRuns || run.size() == 1 || (run.size() > 1 && mx - mn >= 0x1000))
								for (auto &[at, v] : run) refs.push_back({v, at, false});
							run.clear();
						};
						for (size_t o = 0; o + 4 <= sg.data.size(); o += 4) {
							uint32_t at = sg.vaddr + static_cast<uint32_t>(o);
							uint32_t v = static_cast<uint32_t>(sg.data[o]) | (static_cast<uint32_t>(sg.data[o + 1]) << 8) |
							             (static_cast<uint32_t>(sg.data[o + 2]) << 16) | (static_cast<uint32_t>(sg.data[o + 3]) << 24);
							if (!in_code_range(at) && !cov(at) && in_code_range(v)) run.emplace_back(at, v);
							else flush_run();
						}
						flush_run();
					}
				}
				std::map<uint32_t, uint32_t> cand; // target -> first site (ascending targets)
				for (const CodeRef &r : refs) {
					uint32_t a = r.target;
					if ((a & 3) || !in_code_range(a) || img.is_excluded(a) || entries.count(a) || cov(a)) continue;
					uint32_t w;
					if (!img.read32(a, w) || !decode(a, w).valid()) continue;
					if (r.from_code) {
						uint32_t o = owner(a);
						if (o && o == owner(r.site) && a < extent[o]) {
							if (internal_seen.insert(a).second) internal_ptrs.emplace_back(a, r.site);
							continue;
						}
					}
					if (!entry_like(a)) continue;
					cand.emplace(a, r.site);
				}
				size_t added = 0;
				for (const auto &[a, site] : cand) {
					if (cov(a)) continue; // reached by a candidate accepted earlier in this round
					const FuncAnalysis &fa = analyze(a, limit_of(a));
					bool bad = !fa.problems.empty();
					for (const auto &kv : fa.insns)
						if (!kv.second.valid()) bad = true;
					if (bad) continue;
					for (const auto &kv : fa.insns) set_cov(kv.first);
					entries.insert(a);
					why[a] = "discovered: address taken at " + hex(site);
					taken_added.emplace_back(a, site);
					added++;
				}
				if (!added) break;
				fixpoint();
			}
		}
		std::sort(taken_added.begin(), taken_added.end());
		std::sort(internal_ptrs.begin(), internal_ptrs.end());
	}

	// ---- symbols: unique identifiers -------------------------------------
	for (uint32_t e : entries) {
		auto mit = modules.find(e);
		if (mit != modules.end()) syms[e].module = mit->second;
	}
	{
		std::map<std::string, uint32_t> used;
		for (auto &[a, s] : syms) {
			if (!entries.count(a) || s.name.empty()) continue;
			std::string id = sanitize(s.name);
			if (used.count(id)) id += "_" + hex(a);
			used[id] = a;
			s.ident = id;
		}
	}
	auto sym_of = [&](uint32_t e) -> const Symbol * {
		auto it = syms.find(e);
		return it == syms.end() ? nullptr : &it->second;
	};

	// ---- translation -------------------------------------------------------
	EmitStats stats;
	struct Problem {
		uint32_t addr;
		std::string what;
	};
	std::vector<Problem> problems;
	size_t clean = 0, with_dispatch_jr = 0, with_unimpl = 0;
	uint64_t total_bytes = 0;
	std::set<uint32_t> covered;
	std::map<uint32_t, uint32_t> unresolved_jr_sites;
	std::map<uint32_t, uint32_t> sizes;
	std::set<uint32_t> jt_targets; // targets of resolved jump tables

	const uint32_t lo = entries.empty() ? 0 : (*entries.begin() & ~0xFFFu);
	const uint32_t hi = entries.empty() ? 0 : *entries.rbegin();
	auto bucket = [&](uint32_t a) {
		return static_cast<size_t>((static_cast<uint64_t>(a - lo) * nfiles) / (static_cast<uint64_t>(hi - lo) + 1));
	};
	std::vector<std::string> files(nfiles);

	for (uint32_t e : entries) {
		const FuncAnalysis &fa = analyze(e, limit_of(e));
		sizes[e] = fa.end() - e;
		uint64_t unimpl_before = stats.unimplemented;
		std::string comment = "0x" + hex(e);
		if (const Symbol *s = sym_of(e); s && !s->name.empty()) comment += " " + s->name;
		if (const Symbol *s = sym_of(e); s && !s->module.empty()) comment += " [" + s->module + "]";
		if (!why[e].empty() && (!sym_of(e) || why[e] != sym_of(e)->name)) comment += " -- " + why[e];
		std::string code = emit_function(fa, entries, comment_safe(comment), opt, stats);
		bool has_unimpl = stats.unimplemented != unimpl_before || !fa.problems.empty();
		for (const auto &[a, i] : fa.insns) covered.insert(a);
		for (const std::string &p : fa.problems) problems.push_back({e, p});
		if (stats.unimplemented != unimpl_before)
			problems.push_back({e, std::to_string(stats.unimplemented - unimpl_before) + " unimplemented instruction(s)"});
		for (uint32_t s : fa.unresolved_jr) unresolved_jr_sites[s] = e;
		for (const auto &kv : fa.jump_tables) jt_targets.insert(kv.second.begin(), kv.second.end());
		if (has_unimpl) with_unimpl++;
		else if (!fa.unresolved_jr.empty()) with_dispatch_jr++;
		else clean++;
		total_bytes += code.size();
		files[bucket(e)] += code;
	}

	// ---- write output ----------------------------------------------------
	fs::path out(out_dir);
	std::error_code ec;
	fs::create_directories(out, ec);
	if (ec) {
		std::fprintf(stderr, "ps2recomp: cannot create %s\n", out_dir.c_str());
		return 1;
	}
	size_t rewritten = 0;
	std::string hdr = std::string(kFileHeader) + "#pragma once\n#include \"ps2_abi.h\"\n\n";
	for (uint32_t e : entries) hdr += "void " + func_name(e) + "(ps2_cpu *c);\n";
	bool ok = write_if_changed(out / "ps2_funcs.h", hdr, &rewritten);

	size_t largest = 0;
	for (size_t k = 0; k < nfiles; k++) {
		// Local prototypes: every ps2f_XXXXXXXX referenced in this file.
		std::set<std::string> refs;
		const std::string &body = files[k];
		for (size_t p = body.find("ps2f_"); p != std::string::npos; p = body.find("ps2f_", p + 13))
			if (p + 13 <= body.size()) refs.insert(body.substr(p, 13));
		std::string protos;
		for (const std::string &r : refs) protos += "void " + r + "(ps2_cpu *c);\n";
		char nm[32];
		std::snprintf(nm, sizeof nm, "ps2_funcs_%03zu.c", k);
		std::string text = std::string(kFileHeader) + "#include \"ps2_ops.h\"\n\n" + protos + "\n" + body;
		largest = std::max(largest, text.size());
		ok &= write_if_changed(out / nm, text, &rewritten);
	}
	for (size_t k = nfiles;; k++) { // stale chunks from a run with more files
		char nm[32];
		std::snprintf(nm, sizeof nm, "ps2_funcs_%03zu.c", k);
		if (!fs::remove(out / nm, ec)) break;
	}

	std::string disp = std::string(kFileHeader) + "#include \"ps2_funcs.h\"\n\nconst ps2_func_entry ps2_recomp_functions[] = {\n";
	for (uint32_t e : entries) disp += "\t{0x" + hex(e) + "u, " + func_name(e) + "},\n";
	disp += "};\nconst uint32_t ps2_recomp_function_count = " + std::to_string(entries.size()) + "u;\n\n";
	disp += "/* C++ static constructors in .ctors order (the game's own startup walks the\n"
	        " * table through ps2_call_indirect; listed here for runtimes that bypass it). */\n";
	disp += "const uint32_t ps2_recomp_ctors[] = {";
	for (size_t k = 0; k < ctors.size(); k++) disp += std::string(k % 8 ? " " : "\n\t") + "0x" + hex(ctors[k]) + "u,";
	if (ctors.empty()) disp += "0u";
	disp += "\n};\nconst uint32_t ps2_recomp_ctor_count = " + std::to_string(ctors.size()) + "u;\n";
	ok &= write_if_changed(out / "ps2_dispatch.c", disp, &rewritten);

	// Symbol table, name macros, linker aliases.
	std::string nmc = std::string(kFileHeader) + "#include \"ps2_recomp.h\"\n\nconst ps2_recomp_symbol ps2_recomp_symbols[] = {\n";
	std::string nmh = std::string(kFileHeader) +
	                  "/* Named EE functions: PS2_ADDR_<name> (entry address) and PS2_FUNC_<name>\n"
	                  " * (the ps2f_ symbol; usable to call it or to define an HLE override). */\n#pragma once\n\n";
	std::string aliases;
	size_t named = 0;
	for (uint32_t e : entries) {
		const Symbol *s = sym_of(e);
		std::string name = s && !s->name.empty() ? "\"" + c_escape(s->name) + "\"" : "0";
		std::string mod = s && !s->module.empty() ? "\"" + c_escape(s->module) + "\"" : "0";
		nmc += "\t{0x" + hex(e) + "u, " + std::to_string(sizes[e]) + "u, " + name + ", " + mod + "},\n";
		if (s && !s->ident.empty()) {
			named++;
			nmh += "#define PS2_ADDR_" + s->ident + " 0x" + hex(e) + "u\n";
			nmh += "#define PS2_FUNC_" + s->ident + " " + func_name(e) + "\n";
			aliases += "_" + func_name(e) + " _ee_" + s->ident + "\n";
		}
	}
	nmc += "};\nconst uint32_t ps2_recomp_symbol_count = " + std::to_string(entries.size()) + "u;\n";
	ok &= write_if_changed(out / "ps2_names.c", nmc, &rewritten);
	ok &= write_if_changed(out / "ps2_names.h", nmh, &rewritten);
	ok &= write_if_changed(out / "ps2_aliases.txt", aliases, &rewritten);

	// ---- report ------------------------------------------------------------
	std::ostringstream r;
	auto secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
	r << "ps2recomp report\n================\n";
	r << "functions.csv rows:          " << defs.size() << " (" << csv_rejected << " rejected: not in code, "
	  << csv_excluded << " in excluded ranges)\n";
	r << ".ctors entries:              " << ctors.size() << " (" << ctor_new << " not already in CSV)\n";
	r << "CSV entries:                 " << csv_entries << "\n";
	r << "discovered entries:          " << (entries.size() - csv_entries) << " (" << discovered_branch
	  << " call/branch targets, " << taken_added.size() << " address-taken; " << passes << " passes)\n";
	r << "total functions emitted:     " << entries.size() << " (" << named << " named)\n";
	r << "  fully translated:          " << clean << "\n";
	r << "  with runtime-dispatched jr:" << with_dispatch_jr << "\n";
	r << "  with unimplemented insns:  " << with_unimpl << "\n";
	r << "unique instructions covered: " << covered.size() << " (" << covered.size() * 4 << " bytes)\n";
	r << "instructions emitted:        " << stats.instructions << " (incl. duplicated delay slots/overlaps)\n";
	r << "jump tables resolved:        " << stats.jump_tables << "\n";
	r << "indirect jr (dispatch):      " << stats.indirect_jumps << "\n";
	r << "branches in delay slots:     " << stats.delay_slot_branches << "\n";
	r << "unimplemented sites:         " << stats.unimplemented << "\n";
	r << "C output:                    " << nfiles << " files, " << total_bytes << " bytes (largest " << largest
	  << "), " << rewritten << " file(s) rewritten\n";
	r << "time:                        " << secs << " s\n\n";

	r << "Unhandled encodings (key = major<<8 | sub-op), count:\n";
	if (stats.invalid_words.empty()) r << "  (none)\n";
	for (const auto &[k, n] : stats.invalid_words) {
		char b[64];
		std::snprintf(b, sizeof b, "  op=0x%02x sub=0x%02x  %llu\n", k >> 8, k & 0xFF, static_cast<unsigned long long>(n));
		r << b;
	}

	r << "\nInstruction counts by class:\n";
	std::map<std::string, uint64_t> by_class;
	for (size_t k = 0; k < stats.op_count.size(); k++)
		if (stats.op_count[k]) by_class[op_class_name(op_class(static_cast<Op>(k)))] += stats.op_count[k];
	for (const auto &[c, n] : by_class) r << "  " << c << ": " << n << "\n";

	r << "\nOpcode histogram (" << std::count_if(stats.op_count.begin(), stats.op_count.end(), [](uint64_t v) { return v != 0; })
	  << " distinct of " << (static_cast<size_t>(Op::COUNT) - 1) << " supported):\n";
	std::vector<std::pair<uint64_t, Op>> hist;
	for (size_t k = 0; k < stats.op_count.size(); k++)
		if (stats.op_count[k]) hist.emplace_back(stats.op_count[k], static_cast<Op>(k));
	std::sort(hist.begin(), hist.end(), [](auto &a, auto &b) { return a.first != b.first ? a.first > b.first : a.second < b.second; });
	for (auto &[n, op] : hist) r << "  " << op_mnemonic(op) << " " << n << "\n";

	r << "\nUnresolved jr sites (site -> function), dispatched at runtime:\n";
	for (const auto &[s, f] : unresolved_jr_sites) r << "  " << hex(s) << " in " << func_name(f) << "\n";

	// Data words (outside the code ranges) that point into code: every target should be a
	// function entry or a target of a resolved jump table.
	{
		std::set<uint32_t> d_entry, d_jt, d_other_cov, d_uncov;
		for (const Segment &sg : img.segments)
			for (size_t o = 0; o + 4 <= sg.data.size(); o += 4) {
				uint32_t at = sg.vaddr + static_cast<uint32_t>(o);
				uint32_t v = static_cast<uint32_t>(sg.data[o]) | (static_cast<uint32_t>(sg.data[o + 1]) << 8) |
				             (static_cast<uint32_t>(sg.data[o + 2]) << 16) | (static_cast<uint32_t>(sg.data[o + 3]) << 24);
				if (in_code_range(at) || covered.count(at) || !in_code_range(v)) continue;
				if (entries.count(v)) d_entry.insert(v);
				else if (jt_targets.count(v)) d_jt.insert(v);
				else if (covered.count(v)) d_other_cov.insert(v);
				else d_uncov.insert(v);
			}
		r << "\nData words pointing into code (distinct targets): " << d_entry.size() << " function entries, " << d_jt.size()
		  << " resolved jump-table targets, " << d_other_cov.size() << " other reached code, " << d_uncov.size()
		  << " unreached (data that merely looks like a code address, or missed code):\n";
		for (uint32_t v : d_other_cov) r << "  reached, not entry/table target: " << hex(v) << "\n";
		for (uint32_t v : d_uncov) r << "  unreached: " << hex(v) << "\n";
	}

	r << "\nAddress-taken functions added (entry <- first reference):\n";
	for (const auto &[a, s] : taken_added) r << "  " << hex(a) << " <- " << hex(s) << "\n";
	r << "\nCode pointers into a function's own body (labels, not entries; e.g. setjmp receivers):\n";
	for (const auto &[a, s] : internal_ptrs) r << "  " << hex(a) << " <- " << hex(s) << "\n";

	r << "\nProblems:\n";
	for (const Problem &p : problems) r << "  " << func_name(p.addr) << ": " << p.what << "\n";
	ok &= write_if_changed(out / "recomp_report.txt", r.str());

	if (!quiet) {
		std::string rep = r.str();
		std::fwrite(rep.data(), 1, rep.find("\nUnhandled encodings"), stdout);
		std::printf("\nfull report: %s\n", (out / "recomp_report.txt").string().c_str());
	}
	if (!ok) {
		std::fprintf(stderr, "ps2recomp: failed writing output\n");
		return 1;
	}
	return 0;
}
