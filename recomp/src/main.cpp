constexpr bool kSkipTableRuns = false;

struct CodeRef {
	uint32_t target;
	uint32_t site; // instruction address (lui) or data word address
	bool from_code;
};

// lui rX, hi ; ... ; addiu/ori rY, rX, lo (within 16 instructions, rX not redefined)
void scan_code_constants(const FuncAnalysis &fa, std::vector<CodeRef> &out)
{
	for (auto it = fa.insns.begin(); it != fa.insns.end(); ++it) {
		const Insn &lui = it->second;
		if (lui.op != Op::LUI || lui.rt == 0) continue;
		auto jt = std::next(it);
		for (int n = 0; n < 16 && jt != fa.insns.end(); n++, ++jt) {
			const Insn &i = jt->second;
			if (jt->first != lui.pc + 4u * (n + 1)) break; // gap in reached code
			if ((i.op == Op::ADDIU || i.op == Op::DADDIU || i.op == Op::ORI) && i.rs == lui.rt) {
				uint32_t v = i.op == Op::ORI ? ((lui.uimm << 16) | i.uimm) : ((lui.uimm << 16) + static_cast<uint32_t>(i.imm));
				out.push_back({v, lui.pc, true});
			}
			if (insn_gpr_dest(i) == lui.rt || i.flow != Flow::None) break;
		}
	}
}

