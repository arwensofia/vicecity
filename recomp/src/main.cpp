// ps2recomp: SLUS_205.52 (R5900 ELF) + function list -> C sources in recomp_out/.
//
//   ps2recomp --elf game/SLUS_205.52 --functions out/functions.csv --out recomp_out \
//             [--config recomp/config/SLUS_205.52.cfg] [--names tools/library_names.csv] \
//             [--modules out/modules.csv] [--files 64]
//   ps2recomp --elf game/SLUS_205.52 --disasm 0x0011d088 32
//
// Output (all derived from the game; recomp_out/ is git-ignored):
//   ps2_funcs.h          prototypes of every recompiled function
//   ps2_funcs_NNN.c      function bodies (weak definitions); exactly --files files,
//                        function -> file by fixed address bucket so that a local
//                        change only rewrites the files it touches. Each file
//                        declares only the functions it uses (no shared header
//                        besides ps2_ops.h), so adding an entry does not force a
//                        full rebuild.
//   ps2_dispatch.c       ps2_recomp_functions[] / ps2_recomp_ctors[]
//   ps2_names.c          ps2_recomp_symbols[]: entry, size, name, module (see ps2_recomp.h)
//   ps2_names.h          PS2_ADDR_<name> / PS2_FUNC_<name> for named functions
//   ps2_aliases.txt      ld64 -alias_list: _ps2f_XXXXXXXX -> _ee_<name> (debugger symbols)
//   recomp_report.txt    coverage / problem report
// Files are only rewritten when their content changes.
