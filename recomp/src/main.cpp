struct Symbol {
	std::string name;   // display name (as in the source CSV)
	std::string module; // library / module, may be empty
	std::string ident;  // unique C identifier stem (alias = "ee_" + ident), empty if unnamed
	int rank = -1;      // quality of `name` (higher wins)
};

std::string sanitize(const std::string &n)
{
	std::string r;
	for (char ch : n) r.push_back((std::isalnum(static_cast<unsigned char>(ch)) || ch == '_') ? ch : '_');
	if (!r.empty() && std::isdigit(static_cast<unsigned char>(r[0]))) r = "_" + r;
	return r;
}

std::string c_escape(const std::string &s)
{
	std::string r;
	for (char ch : s) {
		if (ch == '"' || ch == '\\') r.push_back('\\');
		if (static_cast<unsigned char>(ch) < 0x20) continue;
		r.push_back(ch);
	}
	return r;
}

std::string comment_safe(std::string s)
{
	for (size_t p; (p = s.find("*/")) != std::string::npos;) s.replace(p, 2, "* /");
	return s;
}

// library_names.csv: address,namespace,name,kind,confidence,evidence
bool load_library_names(const std::string &path, std::map<uint32_t, Symbol> &syms, std::string &err)
{
	std::vector<std::string> hdr;
	std::vector<std::vector<std::string>> rows;
	if (!read_csv(path, hdr, rows, err)) return false;
	auto col = [&](const char *n) {
		for (size_t k = 0; k < hdr.size(); k++)
			if (hdr[k] == n) return static_cast<int>(k);
		return -1;
	};
	int ca = col("address"), cn = col("namespace"), cname = col("name"), ck = col("kind"), cc = col("confidence");
	if (ca < 0 || cname < 0) {
		err = path + ": missing address/name columns";
		return false;
	}
	for (const auto &r : rows) {
		auto get = [&](int k) { return k >= 0 && k < static_cast<int>(r.size()) ? r[k] : std::string(); };
		std::string name = get(cname), kind = get(ck), conf = get(cc);
		if (name.empty() || kind == "note") continue;
		uint32_t a;
		try {
			a = parse_hex(get(ca));
		} catch (...) {
			continue;
		}
		int rank = 100 + (conf == "high" ? 30 : conf == "medium" ? 20 : 10) + (kind == "func" ? 3 : kind == "label" ? 2 : 1);
		Symbol &s = syms[a];
		if (rank > s.rank) {
			s.name = name;
			s.rank = rank;
			if (!get(cn).empty()) s.module = get(cn);
		}
	}
	return true;
}

// out/modules.csv: address,size,module,...
bool load_modules(const std::string &path, std::map<uint32_t, std::string> &mods, std::string &err)
{
	std::vector<std::string> hdr;
	std::vector<std::vector<std::string>> rows;
	if (!read_csv(path, hdr, rows, err)) return false;
	int cm = -1;
	for (size_t k = 0; k < hdr.size(); k++)
		if (hdr[k] == "module") cm = static_cast<int>(k);
	if (cm < 0) {
		err = path + ": no module column";
		return false;
	}
	for (const auto &r : rows) {
		if (r.size() <= static_cast<size_t>(cm) || r[cm].empty()) continue;
		try {
			mods[parse_hex(r[0])] = r[cm];
		} catch (...) {
		}
	}
	return true;
}

